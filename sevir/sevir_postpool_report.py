"""CasCast cascade vs its backbone under three controls, every pooling.

Reads results/revision/postpool/sevir_postpool_{cascast_det,cascast_cascade}.json from
sevir_pool_then_calibrate.py and writes SEVIR_POSTPOOL.md beside them.
"""
import json
from pathlib import Path

import sys as _sys
_sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import paths as P  # noqa: E402
RES = P.RESULTS / "revision" / "postpool"
KINDS = [("raw", "raw"), ("pre", "pre-pooling map (paper)"),
         ("post_grid", "post-pooling map, 1001 knots"),
         ("post_exact", "post-pooling map, exact")]


def load(a):
    d = json.loads((RES / f"sevir_postpool_{a}.json").read_text())
    return d, {(r["pooling"], r["threshold"]): r for r in d["table"]}


def main():
    dd, det = load("cascast_det")
    dc, cas = load("cascast_cascade")
    lines = ["# CasCast cascade vs backbone with the map fitted after pooling", "",
             "Generated by `sevir/sevir_postpool_report.py` from "
             "`sevir_pool_then_calibrate.py`. Evaluation half, 936 events.", "",
             f"Reproduction check against the released per-cell scores: max |ΔCSI| = "
             f"{dd['max_abs_check']:.1e} (backbone), {dc['max_abs_check']:.1e} (cascade).", "",
             "Each cell gives the absolute CSI gap (cascade − backbone) and, in "
             "brackets, the cascade's relative gain.", ""]
    hdr = "| Pooling | τ | " + " | ".join(n for _, n in KINDS) + " | Gap removed, pre | Gap removed, post exact |"
    lines += [hdr, "|" + "---|" * (len(KINDS) + 4)]
    keys = sorted(det, key=lambda k: (["none", "avg4", "max4", "avg16", "max16"].index(k[0]), k[1]))
    for k in keys:
        cells, gaps = [], {}
        for kind, _ in KINDS:
            a, b = det[k][f"csi_{kind}"], cas[k][f"csi_{kind}"]
            gaps[kind] = b - a
            rel = f"{(b - a) / a:+.1%}" if a > 0 else "n/a"
            cells.append(f"{b - a:+.4f} ({rel})")
        def red(kind):
            return f"{1 - gaps[kind] / gaps['raw']:.0%}" if gaps["raw"] else "n/a"
        lines.append(f"| {k[0]} | {k[1]} | " + " | ".join(cells)
                     + f" | {red('pre')} | {red('post_exact')} |")
    lines += ["", "Calibration-half bias check: under the exact post-pooling map, "
              "evaluation-half pooled bias per arm at τ = 219:", ""]
    for m in ["none", "avg4", "max4", "avg16", "max16"]:
        lines.append(f"- {m}: backbone {det[(m, 219)]['bias_post_exact']:.3f}, "
                     f"cascade {cas[(m, 219)]['bias_post_exact']:.3f} "
                     f"(raw {det[(m, 219)]['bias_raw']:.3f} / {cas[(m, 219)]['bias_raw']:.3f})")
    out = RES / "SEVIR_POSTPOOL.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
